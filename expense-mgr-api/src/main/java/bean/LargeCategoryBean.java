package bean;

public class LargeCategoryBean {
    private int largeId;
    private String largeName;

    public LargeCategoryBean() {}

    public int getLargeId() { return largeId; }
    public void setLargeId(int largeId) { this.largeId = largeId; }

    public String getLargeName() { return largeName; }
    public void setLargeName(String largeName) { this.largeName = largeName; }
}
